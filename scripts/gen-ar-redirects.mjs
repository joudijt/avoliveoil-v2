/* Every target must be a page that exists now, or the redirect lands on the SPA
   fallback. English article slugs come from slugs.json, product slugs from
   infusedSlugs.json — the same tables the prerenderer builds pages from. */
const SLUGS = JSON.parse(readFileSync(join(ROOT, 'src/content/articles/slugs.json'), 'utf8'));
const INFUSED = JSON.parse(readFileSync(join(ROOT, 'src/data/infusedSlugs.json'), 'utf8'));
const realTargets = new Set([
  ...Object.values(SLUGS).filter((s) => s.en).map((s) => `blog/${s.en}`),
  ...INFUSED.map((s) => `products/${s}`),
]);

const SLUG_RE = /^[a-z0-9-]+$/;
let failed = false;
const seen = new Set();
for (const [from, to] of ARTICLES) {
  if (!SLUG_RE.test(from)) { console.error(`✗ bad old slug ${from}`); failed = true; }
  if (seen.has(from)) { console.error(`✗ duplicate old slug ${from}`); failed = true; }
  seen.add(from);
  if (!realTargets.has(to)) { console.error(`✗ /ar/blog/${from} -> /en/${to}: target is not a real EN page`); failed = true; }
}
if (ARTICLES.length !== 38) { console.error(`✗ expected 38 Arabic articles, table has ${ARTICLES.length}`); failed = true; }
if (failed) process.exit(1);

const block = [
  BEGIN,
  '  # Arabic was removed from the site on 2026-10-01. Every old /ar URL 301s to',
  '  # its closest English page. Do not hand-edit: change the table in the script',
  '  # and re-run it. [NC]: /AR/... and /Ar/... redirect in one hop too.',
  ...ARTICLES.map(([from, to]) => `  RewriteRule ^ar/blog/${from}/?$ /en/${to} [NC,R=301,L]`),
  '  RewriteRule ^ar/products/([a-z0-9-]+)/?$ /en/products/$1 [NC,R=301,L]',
  '  RewriteRule ^ar/(products|shop|why-us|contact|blog)/?$ /en/$1 [NC,R=301,L]',
  '  RewriteRule ^ar/?$ /en [NC,R=301,L]',
  '  RewriteRule ^ar/.*$ /en [NC,R=301,L]',
  `  ${END}`,
].join('\n');

const raw = readFileSync(HTACCESS, 'utf8');
const eol = raw.includes('\r\n') ? '\r\n' : '\n';
const text = raw.replace(/\r\n/g, '\n');

const b = text.indexOf(BEGIN);
const e = b === -1 ? -1 : text.indexOf(END, b);
if (b === -1 || e === -1 || text.indexOf(BEGIN, b + 1) !== -1) {
  console.error(
    `✗ public/.htaccess must contain exactly one "${BEGIN}" … "${END}" pair ` +
      '(placed right after the https and www -> apex redirects)'
  );
  process.exit(1);
}
const lineStart = text.lastIndexOf('\n', b) + 1;
const next = text.slice(0, lineStart) + '  ' + block + text.slice(e + END.length);

// Nothing may serve or rewrite a request before the block: every RewriteRule above
// it must be an external redirect (the https and www -> apex ones).
const early = next
  .slice(0, next.indexOf(BEGIN))
  .split('\n')
  .filter((l) => /^\s*RewriteRule\b/.test(l) && !/\[(?:[^\]]*,)?R=30[18]\b/.test(l));
if (early.length) {
  console.error(`✗ the ar-redirects block must come before every non-redirect rule; above it:\n  ${early.join('\n  ')}`);
  process.exit(1);
}

const out = next.replace(/\n/g, eol);
if (CHECK) {
  if (out !== raw) {
    console.error('✗ public/.htaccess ar-redirects block is out of date — run: node scripts/gen-ar-redirects.mjs');
    process.exit(1);
  }
  console.log(`✓ public/.htaccess ar-redirects up to date (${ARTICLES.length} articles + 4 catch-all rules)`);
} else {
  writeFileSync(HTACCESS, out, 'utf8');
  console.log(`✓ wrote ${ARTICLES.length} article redirects + 4 catch-all rules into public/.htaccess`);
}
