def emit(src_name: str, box, size, dest: Path, *, quality: int, webp: bool,
         max_kb: int = 130) -> str:
    im = Image.open(SRC / src_name)
    if box[2] > im.width or box[3] > im.height:
        raise SystemExit(f"{dest.name}: box {box} outside {src_name} {im.size}")
    if (box[2] - box[0]) < size[0]:
        raise SystemExit(f"{dest.name}: box is {box[2] - box[0]} px wide, "
                         f"would upscale to {size[0]} — refusing")
    crop = im.crop(box).convert("RGB").resize(size, Image.LANCZOS)
    dest.parent.mkdir(parents=True, exist_ok=True)
    # Step the quality down until the file fits the round's per-image budget. A detailed
    # grove photo lands twice the size of a studio still at the same quality number.
    q = quality
    while True:
        if webp:
            crop.save(dest, "WEBP", quality=q, method=6)
        else:
            crop.save(dest, "JPEG", quality=q, optimize=True, progressive=True)
        if dest.stat().st_size <= max_kb * 1024 or q <= 55:
            break
        q -= 5
    return (f"{dest.relative_to(ROOT)}  {size[0]}x{size[1]}  "
            f"{dest.stat().st_size // 1024} KB  q{q}")


def main() -> None:
    total = 0
    print("---- heroes (crops of repo photography) ----")
    for aid, (src, box) in HERO_CROPS.items():
        line = emit(src, box, HERO, OUT / f"{aid}-hero.webp", quality=82, webp=True)
        total += (OUT / f"{aid}-hero.webp").stat().st_size
        print(line)

    print("\n---- OG cards ----")
    for aid, (src, box) in OG_CROPS.items():
        line = emit(src, box, CARD, OG / f"blog-{aid}.jpg", quality=80, webp=False)
        total += (OG / f"blog-{aid}.jpg").stat().st_size
        print(line)

    print(f"\nderived bytes: {total / 1024 / 1024:.2f} MB")


if __name__ == "__main__":
    main()
